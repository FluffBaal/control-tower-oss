// SPEC-MEMORY — first-load import of the legacy free-form markdown files into versioned entries.
// Runs ONCE per project (the facade gates it on hasProject), never invents authorship or approval, and
// RENAMES the originals to `<file>.imported-<ts>` rather than deleting them, so a rollback is a rename
// back. Idempotent by construction: seedImport dedups on (origin, file, content-sha) and upsertKeyed on
// the key, so a re-run after a failed rename is a no-op, not a duplicate.

import { existsSync, readFileSync, renameSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { MEMORY_KINDS, viewFileFor } from '../../shared/memory.js';
import { parseLegacy, isGeneratedView, neutralizeReservedSyntax, TEST_KIT_KEY } from './views.js';
import { fitImportedBody, BODY_MAX } from './schema.js';
import type { MemoryStore } from './store.js';

/**
 * Make a legacy candidate importable WITHOUT losing it. A caller-supplied body is REFUSED by the store for
 * reserved view syntax or an over-cap length; legacy text gets neither refusal, because the operator who
 * wrote it could not have known the tokens, and a refused import would drop the note (the file is already
 * archived by the time phase 2 runs). schema.ts fitImportedBody does both: reserved tokens are neutralized
 * (the HTML-comment tokens become `<!-- x-ct:… -->`, still invisible in rendered markdown; a visible
 * reserved line gains ` (legacy)`), and an over-BODY_MAX body is cut on line boundaries — LOUDLY here, and
 * the archived original keeps every byte. The result is what BOTH store paths accept: seedImport re-fits it
 * (a no-op — fitImportedBody is idempotent) and the strict upsertKeyed's assertBody passes it.
 */
function importable(body: string, file: string): string {
  if (neutralizeReservedSyntax(body).length > BODY_MAX) {
    console.error(`[memory] legacy note in ${file} exceeds ${BODY_MAX} chars — truncated on import (the archived original is intact)`);
  }
  return fitImportedBody(body);
}

function renameOut(abs: string, ts: number): void {
  try {
    renameSync(abs, `${abs}.imported-${ts}`);
  } catch (err) {
    // Best-effort: a failed rename just means the next boot re-reads the file, and the content-sha dedup
    // makes the re-import a no-op — no duplicate, no crash.
    console.error(`[memory] could not archive ${abs}: ${(err as Error).message}`);
  }
}

/**
 * Import a project's legacy decisions/gotchas/glossary markdown into the store as entries, then archive
 * the originals. Returns the number of entries imported. The three view files are REGENERATED by the
 * facade after this returns, so the same filenames become the generated views.
 *
 * TWO PHASES, deliberately: every store mutation fires the store's onChange hook, which the integrator
 * wires to regenerate ALL THREE markdown views from the store's CURRENT state. If we read-import-archive
 * one file at a time, the first import's hook would overwrite the not-yet-read view files (gotchas.md,
 * glossary.md) with header-only content BEFORE we read them — and we'd then import that clobbered
 * placeholder and archive it, destroying the operator's real content. So phase 1 reads AND archives every
 * legacy file up front (the originals are safe under .imported-<ts>, and buffered here), and only phase 2
 * mutates the store — by which point no unread file remains on disk for a hook to clobber.
 */
export function importLegacy(store: MemoryStore, pid: string, dir: string): number {
  const ts = Date.now();
  // Phase 1: read + archive ALL legacy files before touching the store.
  const pending: { kind: (typeof MEMORY_KINDS)[number]; file: string; text: string; mtime: number }[] = [];
  for (const kind of MEMORY_KINDS) {
    const file = viewFileFor(kind);
    const abs = join(dir, file);
    if (!existsSync(abs)) continue;
    let text: string;
    let mtime: number;
    try {
      text = readFileSync(abs, 'utf8');
      mtime = statSync(abs).mtimeMs;
    } catch (err) {
      console.error(`[memory] could not read legacy ${abs}: ${(err as Error).message}`);
      continue;
    }
    // A generated view left on disk (no entries.json beside it) is OUR markup, not legacy content:
    // neither imported nor archived — importing it would mint entries out of the header line.
    if (isGeneratedView(text)) continue;
    renameOut(abs, ts); // archive NOW (before any hook-driven writeViews can overwrite it)
    if (text.trim()) pending.push({ kind, file, text, mtime });
  }
  // Phase 2: import from the buffered text.
  let imported = 0;
  for (const { kind, file, text, mtime } of pending) {
    for (const cand of parseLegacy(text)) {
      const body = importable(cand.body, file);
      if (cand.key === TEST_KIT_KEY) {
        // The Tower-authored e2e test-kit block: a keyed upsert, so it stays the single managed entry.
        store.upsertKeyed(pid, cand.key, { kind, body, author: { kind: 'tower', reason: 'legacy-import' } });
      } else {
        // The dedup key hashes the ORIGINAL bytes, so a re-import of the same archived file is a no-op.
        const sha256 = createHash('sha256').update(cand.body).digest('hex');
        store.seedImport(pid, { kind, body, origin: 'imported', importedFrom: { file, sha256, mtime } });
      }
      imported++;
    }
  }
  return imported;
}
